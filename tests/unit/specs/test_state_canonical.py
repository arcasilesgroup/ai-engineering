    missing = [name for name in REQUIRED_FILES if not (STATE_DIR / name).is_file()]
    assert not missing, (
        f"Required state files missing from {STATE_DIR}: {missing}. "
        "These define the canonical state surface (spec-125 D-125-09)."
    )


